/** 取图标；没登记就回落到 spark，绝不返回空（空会在 svg 里留下一个看不见的洞） */
export function glyph(key: string | undefined): Glyph {
  return (key && ARCH_GLYPHS[key]) || ARCH_GLYPHS.spark;
}

/** 把图标摆到 (x, y)，尺寸 size×size */
export function glyphSvg(key: string | undefined, x: number, y: number, size: number, color: string): string {
  const s = size / 24;
  return (
    `<g transform="translate(${r2(x)} ${r2(y)}) scale(${r2(s, 4)})" style="color:${color}">` +
    `${glyph(key)}</g>`
  );
}

function r2(n: number, p = 2): number {
  const m = 10 ** p;
  return Math.round(n * m) / m;
}
